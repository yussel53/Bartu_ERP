function flattenScreens(screens: MenuScreen[]): MenuScreen[] {
  return screens.flatMap((s) => [s, ...(s.children ? flattenScreens(s.children) : [])]);
}

export function getAllScreens(): MenuScreen[] {
  return APP_MODULES.flatMap((m) => m.groups.flatMap((g) => flattenScreens(g.screens)));
}

export function getScreenByPath(path: string): MenuScreen | undefined {
  return getAllScreens().find((s) => s.path === path);
}

export function getModuleByPath(path: string): AppModule | undefined {
  return APP_MODULES.find((m) => m.path === path);
}
