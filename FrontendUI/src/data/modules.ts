function cols(...pairs: [string, string][]): ListColumn[] {
  return pairs.map(([key, label]) => ({ key, label }));
}

function screen(
  partial: Omit<MenuScreen, 'listColumns' | 'sampleRows'> & {
    listColumns?: ListColumn[];
    sampleRows?: Record<string, string | number>[];
  },
): MenuScreen {
  return {
    listColumns: partial.listColumns || cols(['code', 'Kod'], ['title', 'Ad'], ['status', 'Durum']),
    sampleRows: partial.sampleRows || [{ id: 1, code: '001', title: 'Örnek', status: 'Aktif' }],
    ...partial,
  };
}

